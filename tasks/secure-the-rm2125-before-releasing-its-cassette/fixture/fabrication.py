"""Generate the printable carriage, in mm, from native surfaces plus drilled bushes."""
from pathlib import Path
import sys,json,numpy as np
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parent))
import task as t

def primitive(s,origin):
 p=(np.array(s.at)-origin)*1000;v=np.array(s.size)*1000
 geom='cube('+json.dumps(v.tolist())+',center=true);' if s.kind=='box' else ('rotate([90,0,0]) ' if s.axis=='y' else '')+f'cylinder(r={v[0]},h={v[1]},center=true);'
 return 'translate('+json.dumps(p.tolist())+') '+geom
origin=np.array(t.head.origin)*1000
s=['// Generated by fabrication.py. Part-local millimetres.',
 'module carriage_print(){difference(){union(){']
# Native head surfaces, mounting pad and crank-clear low bridge. Metal tubes and spring
# bridge are separate fittings, excluded from this print.
for i,shape in enumerate(t.head.shapes):
 if i not in (*range(10),*range(16,20)):continue
 # First post clears the axle/rotating beam; outer post becomes an integral bearing cheek.
 if i==1:shape=t.bx((.0215,.008,.032),(-.05925,-.021,t.C0+.023))
 s.append(primitive(shape,t.head.origin))
 if i==2:s.append(primitive(t.cyl(.007,.008,(-.0455,.021,t.C0+.0262)),t.head.origin))
s += ['translate('+json.dumps((-origin).tolist())+') {',
 f'for(y=[-60,60])translate([-29,y,{t.C0*1000-48}])cylinder(d=16,h=20,center=true);','}', '}',
 'translate('+json.dumps((-origin).tolist())+') {',
 f'for(y=[-60,60])translate([-29,y,{t.C0*1000-48}])cylinder(d=8.3,h=80,center=true);',
 f'translate([-45.5,21,{t.C0*1000+26.2}])rotate([90,0,0])cylinder(d=4.85,h=14,center=true);',
 f'translate([-41,39,{t.C0*1000-16}])cylinder(d=13.1,h=35,center=true);',
 f'translate([-41,39,{t.C0*1000-16}])rotate([0,90,0])cylinder(d=4.3,h=60,center=true);',
 f'translate([-25.5,39,{t.C0*1000-16}])rotate([0,90,0])cylinder(d=10,h=1.02,center=true);',
 '}}}']
(HERE/'fabrication.scad').write_text('\n'.join(s)+'\n')
print('wrote fabrication.scad; carriage link origin mm:',origin.tolist())
